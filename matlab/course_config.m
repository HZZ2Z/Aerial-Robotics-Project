function C = course_config(P, K, F, M, opt)
%COURSE_CONFIG 组装 Simulink 模型与各 MATLAB Function 所需的全局结构体参数 C。
%   将标称参数 P、LQR 增益 K、功能开关 F（是否使用 KF、是否近似 Q、是否开启风前馈）、
%   滤波器矩阵 M 以及单次仿真工况 opt（质量/惯量摄动、延迟、失锁时间窗、随机种子等）打包。
C = struct('g',P.g,'m',P.m,'J',P.J,'kd',P.kd,'Tmax',P.Tmax,'nmax',P.lqr.nmax, ...
    'm_true',P.m*opt.m_scale,'J_true',P.J*opt.J_scale,'h',opt.dt,'t_end',opt.tfinal, ...
    'use_kf',logical(F.use_est),'use_Qapprox',logical(F.use_Qapprox), ...
    'ff_wind',logical(F.ff_wind),'no_fix',logical(opt.no_fix),'delay',opt.in_delay, ...
    'deg_t0',opt.fix_loss(1),'deg_t1',opt.fix_loss(2), ...
    'wind_t0',P.wind.t0,'wind_mean',P.wind.vmean, ...
    'wind_on',double(ismember(opt.wind_mode, {'mean_only','mean_gust'})), ...
    'gust_on',double(ismember(opt.wind_mode, {'gust_only','mean_gust'})), ...
    'gust_tau',P.wind.tau,'gust_sd',P.wind.sigma,'gust_Ts',P.noise.dt_wind, ...
    'ahrs_dt',P.noise.dt_sensor,'gyro_dt',P.noise.dt_sensor,'gnss_dt',P.noise.dt_gnss, ...
    'r_eta',P.sens.ahrs.r*ones(3,1),'r_w',P.sens.gyro.r*ones(3,1), ...
    'r_gnss',P.sens.gnss.rvec,'r_gnss_deg',P.sens.gnss.rbad, ...
    'seed_ahrs',opt.seed+P.noise.seed_ahrs+(0:2), ...
    'seed_gyro',opt.seed+P.noise.seed_gyro+(0:2), ...
    'seed_gnss',opt.seed+P.noise.seed_gnss+(0:2), ...
    'seed_wind',opt.seed+P.noise.seed_wind+(0:2), ...
    'x0',zeros(12,1),'xh0',zeros(9,1),'eps_d',P.lqr.eps_d,'K',K, ...
    'ulin_min',[-P.Ttrim;-P.lqr.nmax],'ulin_max',[P.Tmax-P.Ttrim;P.lqr.nmax], ...
    'A_kf',M.A,'B_kf',M.B,'C_kf',M.C,'L_rtk',M.Lg,'L_deg',M.Lb);
% 课程主模型仅支持 9 维随机游走滤波器及硬切换增益模式
assert(M.nx == 9 && M.blend_s == 0, 'Teacher model requires the rw9 hard-switch filter.');
end
